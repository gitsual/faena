            "- A concrete, verifiable goal (\"create X with Y; at the end, check that Z shows\"), with the labels as they appear in the interface; if the interface may be in English or in Spanish, give both.\n" +
            "- Give it the \"done\" signal (\"after Save it shows “Ready”: finish\"), or a small model will keep saving in a loop.\n" +
            $"- If the task will repeat, `{w.Learn}` the first time and `{w.UseSkill}` the next ones.\n" +
            "- For anything delicate, rehearse it first against a local replica of the website, and only then against the real one.\n" +
            "- **Long fields**: when replaying a skill, faena types character by character with a limit of about 10 s per step, so more than about 500 characters do not fit in one go: split it (for example, a variable that is appended to).\n" +
            $"- **The guard** decides by the control's name: a button called \"Post…\" or \"Send…\" counts as sending even if it only adds a step. Instead of opening your hand with `{w.Allow}`, use `{w.AskInFolder}` and answer `respuesta.json` yourself (`{{\"si\": true}}` or `{{\"si\": false}}`) to each `pregunta.json` it leaves in the task's folder, with a narrow whitelist of what the user has authorized.\n", lang));
        if (!string.IsNullOrWhiteSpace(extra))
        {
            var e = extra.Trim();
            var enlace = Path.IsPathRooted(e) ? e : e.Replace('\\', '/');
            sb.Append('\n').Append(T($"Notas propias de este equipo (no las genera faena): [{Path.GetFileName(e)}]({enlace}).\n",
                                     $"Notes of this computer (not generated by faena): [{Path.GetFileName(e)}]({enlace}).\n", lang));
        }
        return sb.ToString();
    }

    /// <summary>One learned skill as its own Agent Skill, faena-&lt;name&gt;/SKILL.md, in <paramref name="lang"/>.</summary>
    public static string SkillDeHabilidad(Habilidad h, string lang, string exe)
    {
        var w = Palabras.De(lang);
        var bash = ExeBash(exe);
        var hueco = new Regex(@"\{([\p{L}\p{N}_]+)\}", RegexOptions.CultureInvariant);
        var ejemplo = hueco.Replace(h.Descripcion, m => h.Parametros.TryGetValue(m.Groups[1].Value, out var v) ? v : m.Value);
        if (ejemplo.Trim().Length == 0) ejemplo = T($"Repetir «{h.Nombre}»", $"Replay “{h.Nombre}”", lang);
        var donde = h.Superficie == "escritorio" ? T("un programa de Windows", "a Windows program", lang) : T("una web", "a website", lang);
        var pasos = Habilidades.Rellenar(h, new Dictionary<string, string>());
        var paran = pasos.Select((p, i) => (i + 1, Desc: Campos.Str(p, "desc")))
            .Where(x => x.Desc.Length != 0 && Guardian.Categoria(Encargo.Nombrado(x.Desc)) is not null && pasos[x.Item1 - 1]["tipo"]?.ToString() == "clic")
            .Select(x => (x.Item1, x.Desc, Cat: Guardian.Categoria(Encargo.Nombrado(x.Desc))!)).ToList();
        var cuando = h.Cuando.Count != 0 ? string.Join(", ", h.Cuando.Take(8)) : "";
        var sb = new StringBuilder();
        sb.Append("---\n");
        sb.Append("name: ").Append(NombreSkill(h)).Append('\n');
        sb.Append("description: ").Append(Yaml(T(
            $"Hacer con faena, en {donde}, lo que ya sabe hacer de memoria: {hueco.Replace(h.Descripcion, m => "<" + m.Groups[1].Value + ">")}. Úsalo cuando el usuario pida exactamente eso con otros datos" + (cuando.Length != 0 ? $" (palabras que lo delatan: {cuando})" : "") + ".",
            $"Do with faena, in {donde}, what it already knows by heart: {hueco.Replace(h.Descripcion, m => "<" + m.Groups[1].Value + ">")}. Use it when the user asks for exactly that with other data" + (cuando.Length != 0 ? $" (words that give it away: {cuando})" : "") + ".", lang))).Append('\n');
        sb.Append("---\n\n");
        sb.Append(Cabecera(lang)).Append("\n\n");
        sb.Append($"# faena: {h.Nombre}\n\n");
        sb.Append(T($"Una habilidad que faena aprendió (`{h.Nombre}`): ", $"A skill faena learned (`{h.Nombre}`): ", lang)).Append(h.Descripcion.TrimEnd().TrimEnd('.')).Append(".\n");
        if (h.Inicio.Length != 0) sb.Append(T($"Empieza en {donde}: `{h.Inicio}`.\n", $"It starts in {donde}: `{h.Inicio}`.\n", lang));
        if (h.Origen.Length != 0 || h.Aprendida.Length != 0)
            sb.Append(T("Aprendida", "Learned", lang)).Append(h.Aprendida.Length != 0 ? $" {h.Aprendida}" : "").Append(h.Origen.Length != 0 ? $" ({h.Origen})" : "").Append(".\n");
        sb.Append(T("Para todo lo general (sesiones, modelos, informe) mira también la skill `faena`.\n\n", "For everything general (sessions, models, the report) see the `faena` skill too.\n\n", lang));

        sb.Append(T("## Parámetros\n\n", "## Parameters\n\n", lang));
        if (h.Parametros.Count == 0) sb.Append(T("Ninguno: siempre hace lo mismo.\n\n", "None: it always does the same.\n\n", lang));
        else
        {
            sb.Append(T("| parámetro | ejemplo |\n|---|---|\n", "| parameter | example |\n|---|---|\n", lang));
            foreach (var (k, v) in h.Parametros) sb.Append($"| `{k}` | {v.Replace("|", "\\|")} |\n");
            sb.Append('\n');
        }

        sb.Append(T("## Cómo se encarga\n\n", "## How to hand it over\n\n", lang));
        sb.Append(T("Con modelo (saca los valores del objetivo, comprueba el final y, si la interfaz ha cambiado, termina la tarea y reescribe la habilidad):\n\n",
                    "With a model (it takes the values from the goal, checks the end and, if the interface changed, finishes the task and rewrites the skill):\n\n", lang));
        sb.Append("```bash\n").Append($"\"{bash}\" {w.Do} \"{ejemplo.Replace("\"", "\\\"")}\" {w.UseSkill} {h.Nombre} {w.Background} {w.Screenshots}\n").Append("```\n\n");
        sb.Append(T("Sin modelo (repite los pasos tal cual con los valores que le des):\n\n", "Without a model (it replays the steps as they are with the values you give):\n\n", lang));
        sb.Append("```bash\n").Append($"\"{bash}\" {w.Do} \"{ejemplo.Replace("\"", "\\\"")}\" {w.UseSkill} {h.Nombre} {w.NoModel}");
        foreach (var (k, v) in h.Parametros) sb.Append($" --param \"{k}={v.Replace("\"", "\\\"")}\"");
        sb.Append($" {w.Background} {w.Screenshots}\n").Append("```\n\n");
        sb.Append(T(
            "**Cuándo con modelo y cuándo sin él**: sin modelo es más rápido y no necesita GPU, pero nadie mira el resultado; úsalo para un proceso mecánico ya probado en la misma pantalla y con valores que ya tienes. Con modelo cuando los valores salen de una frase, cuando la web ha podido cambiar o cuando hay que comprobar que ha quedado bien.\n\n",
            "**When with a model and when without**: without a model it is faster and needs no GPU, but nobody looks at the result; use it for a mechanical procedure already proven on the same screen and with values you already have. With a model when the values come from a sentence, when the website may have changed or when the result has to be checked.\n\n", lang));

        sb.Append(T("## Lo irreversible se para igual\n\n", "## Anything irreversible still stops\n\n", lang));
        sb.Append(T(
            $"Repita con o sin modelo, faena se para antes de enviar, borrar, pagar o aceptar nada que no esté autorizado (salida 3). `{w.Allow} <categoría>` solo con la autorización del usuario para esta tarea.",
            $"With or without a model, faena stops before sending, deleting, paying for or accepting anything that was not allowed (exit code 3). `{w.Allow} <category>` only with the user's authorization for this task.", lang));
        if (paran.Count != 0)
        {
            sb.Append(T(" En esta habilidad se pararán:\n\n", " In this skill these will stop:\n\n", lang));
            foreach (var (n, desc, cat) in paran) sb.Append($"- {T("paso", "step", lang)} {n}: {desc} (`{Guardian.NombreCategoria(cat, lang)}`)\n");
        }
        else sb.Append('\n');
        sb.Append('\n');

        sb.Append(T("## Pasos\n\n", "## Steps\n\n", lang));
        for (var i = 0; i < h.Pasos.Count; i++)
        {
            var d = Campos.Str(h.Pasos[i], "desc");
            sb.Append(i + 1).Append(". ").Append(d.Length != 0 ? d : Campos.Str(h.Pasos[i], "tipo")).Append('\n');
        }
        sb.Append(T($"\nResultado: código de salida 0/1/3 y el informe en la ruta de la última línea (`informe.md`, `informe.json`). El `.toml` de la habilidad: `faena {w.Skills} {(Lengua.Normalizar(lang) == "es" ? "ver" : "show")} {h.Nombre}`.\n",
                    $"\nResult: exit code 0/1/3 and the report at the path on the last line (`informe.md`, `informe.json`). The skill's `.toml`: `faena {w.Skills} {(Lengua.Normalizar(lang) == "es" ? "ver" : "show")} {h.Nombre}`.\n", lang));
        return sb.ToString();
    }
