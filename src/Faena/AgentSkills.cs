        string UseSkill, string NoModel, string Learn, string MaxSteps, string MaxMinutes, string WindowTitle, string AskInFolder, string Folder)
    {
        public static Palabras De(string lang) => Lengua.Normalizar(lang) == "es"
            ? new("hacer", "habilidades", "lista", "--fondo", "--capturas", "--permitir", "--ver", "--habilidad", "--sin-modelo", "--aprender",
                  "--max-pasos", "--max-minutos", "--ventana", "--preguntar-en-carpeta", "--carpeta")
            : new("do", "skills", "list", "--background", "--screenshots", "--allow", "--show", "--use-skill", "--no-model", "--learn",
                  "--max-steps", "--max-minutes", "--window-title", "--ask-in-folder", "--folder");
    }

    /// <summary>The exe for a Bash shell (Git Bash, WSL-less): C:\x\faena.exe → /c/x/faena.exe.</summary>
    internal static string ExeBash(string exe) =>
        Regex.IsMatch(exe, @"^[A-Za-z]:\\") ? "/" + char.ToLowerInvariant(exe[0]) + exe[2..].Replace('\\', '/') : exe.Replace('\\', '/');

