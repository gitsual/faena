// `faena skill install|export|list`: faena writes Agent Skills (the SKILL.md format of Claude Code
// and of the agents that read it) so that another agent knows how to hand faena its errands.
//
// - install: the main skill, `faena/SKILL.md`, generated from what this faena is (the real path of
//   the exe, where it keeps its reports and sessions) and from what was learned using it.
// - export: one learned skill (.toml) as its own Agent Skill, `faena-<name>/SKILL.md`, with its
//   parameters, the exact command and the steps that will stop for permission.
// - list: the Agent Skills faena has written (they carry the marker below).
//
// The text is generated, never edited by hand: same faena, same skill, same file. Notes that only
// make sense on one computer go in a file of their own (LOCAL.md) that --extra points to. An
// existing SKILL.md is never overwritten without --force, and with --force a .bak is kept.
using System.Text;
using System.Text.RegularExpressions;
using Faena.Agente;

namespace Faena;

internal static class AgentSkills
{
    /// <summary>The first line after the front matter of every SKILL.md faena writes; `skill list` looks for it.</summary>
    public const string Marca = "<!-- generated by faena";

    /// <summary>The exe the skills tell agents to run; the tests set a fixed one.</summary>
    internal static Func<string> Exe { get; set; } = ExeDefault;

    /// <summary>The user's home, for --scope user; the tests point it at a temporary folder.</summary>
    internal static Func<string> Home { get; set; } = () => Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);

    private static string ExeDefault()
    {
        var p = Environment.ProcessPath;
        return p is not null && Path.GetFileName(p).Equals("faena.exe", StringComparison.OrdinalIgnoreCase) ? p : "faena";
    }

    private static string T(string es, string en, string lang) => Lengua.T(es, en, lang);

    // --- parser ------------------------------------------------------------------------

    public static void Registrar(ArgParser ap)
    {
        static string T(string es, string en) => Lengua.T(es, en);
        var p = ap.AddSubparser("command", "skill", help: T("skills para agentes (SKILL.md de Claude Code y compatibles) que enseñan a encargarle faenas a faena",
                                                            "Agent Skills (SKILL.md, for Claude Code and compatible agents) that teach how to hand errands to faena"));
        void Comunes(ArgParser d)
        {
            d.Add("--scope", choices: ["user", "project"], @default: "user", help: T("user: ~/.claude/skills; project: .claude/skills de la carpeta actual",
                                                                                  "user: ~/.claude/skills; project: .claude/skills in the current folder"));
            d.Add("--dir", help: T("otra carpeta de skills (en vez de --scope)", "another skills folder (instead of --scope)"));
            d.AddSwitch("--force", help: T("sustituir un SKILL.md que ya exista (deja una copia .bak)", "replace an existing SKILL.md (keeps a .bak copy)"));
        }
        var d = p.AddSubparser("skill_cmd", "install", help: T("escribe la skill faena/SKILL.md", "write the skill faena/SKILL.md"), aliases: "instalar");
        Comunes(d);
        d.Add("--extra", help: T("un archivo de notas propias (p. ej. LOCAL.md) al que remite la última línea", "a file of your own notes (e.g. LOCAL.md) the last line points to"));
        d.Handler = CmdInstalar;
        d = p.AddSubparser("skill_cmd", "export", help: T("convierte una habilidad aprendida en su propia skill faena-<nombre>/SKILL.md",
                                                          "turn a learned skill into its own Agent Skill faena-<name>/SKILL.md"), aliases: "exportar");
        d.Add("skill", es: "habilidad", help: T("el nombre de la habilidad (faena habilidades lista)", "the skill's name (faena skills list)"));
        Comunes(d);
        d.Handler = CmdExportar;
        d = p.AddSubparser("skill_cmd", "list", help: T("las skills que ha escrito faena", "the Agent Skills faena has written"), aliases: "lista");
        d.Add("--dir", help: T("mirar también en esta carpeta de skills", "also look in this skills folder"));
        d.Handler = CmdListar;
    }

    /// <summary>The skills folder for a scope, or --dir.</summary>
    public static string Destino(string? scope, string? dir) =>
        dir is { Length: > 0 } ? Path.GetFullPath(dir)
        : scope == "project" ? Path.Combine(Directory.GetCurrentDirectory(), ".claude", "skills")
        : Path.Combine(Home(), ".claude", "skills");

    private static int CmdInstalar(ParsedArgs args)
    {
        var raiz = Destino(args.Get("scope"), args.Get("dir"));
        try
        {
            var ruta = Instalar(raiz, Lengua.Actual, args.Flag("force"), args.Get("extra"));
            Console.WriteLine(ruta);
            if (args.Get("extra") is { } extra && !File.Exists(Path.IsPathRooted(extra) ? extra : Path.Combine(Path.GetDirectoryName(ruta)!, extra)))
                Console.Error.WriteLine(Lengua.T($"Aviso: {extra} aún no existe; la skill ya remite a él.", $"Warning: {extra} does not exist yet; the skill already points to it."));
            return 0;
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            Console.Error.WriteLine(e.Message);
            return 2;
        }
    }

    private static int CmdExportar(ParsedArgs args)
    {
        var nombre = args.GetRequired("habilidad");
        var h = Habilidades.Cargar(Paths.Habilidades).FirstOrDefault(x => string.Equals(x.Nombre, nombre, StringComparison.OrdinalIgnoreCase));
        if (h is null)
        {
            Console.Error.WriteLine(Lengua.T($"No hay ninguna habilidad «{nombre}» en {Paths.Habilidades}.", $"There is no skill “{nombre}” in {Paths.Habilidades}."));
            return 2;
        }
        try
        {
            Console.WriteLine(Exportar(h, Destino(args.Get("scope"), args.Get("dir")), Lengua.Actual, args.Flag("force")));
            return 0;
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            Console.Error.WriteLine(e.Message);
            return 2;
        }
    }

    private static int CmdListar(ParsedArgs args)
    {
        var raices = new List<string> { Destino("user", null), Destino("project", null) };
        if (args.Get("dir") is { } dir) raices.Add(Destino(null, dir));
        var lista = Listar(raices);
        if (lista.Count == 0) Console.WriteLine(Lengua.T("faena no ha escrito ninguna skill todavía (faena skill install).", "faena has not written any Agent Skill yet (faena skill install)."));
        foreach (var (nombre, ruta) in lista) Console.WriteLine($"{nombre}: {ruta}");
        return 0;
    }

    // --- writing -----------------------------------------------------------------------

    /// <summary>
    /// Writes <paramref name="contenido"/> to <paramref name="ruta"/>. An existing file is only
    /// replaced with <paramref name="force"/>, and then its old text is kept in <c>SKILL.md.bak</c>.
    /// </summary>
    public static void Escribir(string ruta, string contenido, bool force)
    {
        if (File.Exists(ruta))
        {
            if (!force)
                throw new IOException(Lengua.T($"Ya existe {ruta}; usa --force para sustituirlo (se guarda una copia .bak).",
                                               $"{ruta} already exists; use --force to replace it (a .bak copy is kept)."));
            File.Copy(ruta, ruta + ".bak", overwrite: true);
        }
        Directory.CreateDirectory(Path.GetDirectoryName(ruta)!);
        File.WriteAllText(ruta, contenido, new UTF8Encoding(false));
    }

    public static string Instalar(string raiz, string lang, bool force, string? extra = null)
    {
        var ruta = Path.Combine(raiz, "faena", "SKILL.md");
        Escribir(ruta, SkillPrincipal(lang, Exe(), extra), force);
        return ruta;
    }

    public static string Exportar(Habilidad h, string raiz, string lang, bool force)
    {
        var ruta = Path.Combine(raiz, NombreSkill(h), "SKILL.md");
        Escribir(ruta, SkillDeHabilidad(h, lang, Exe()), force);
        return ruta;
    }

    public static string NombreSkill(Habilidad h) => "faena-" + Habilidades.Slug(h.Nombre);

    /// <summary>The skills faena wrote under these folders: (name, SKILL.md), by name.</summary>
    public static List<(string Nombre, string Ruta)> Listar(IEnumerable<string> raices)
    {
        var lista = new List<(string, string)>();
        foreach (var raiz in raices.Distinct(StringComparer.OrdinalIgnoreCase))
        {
            if (!Directory.Exists(raiz)) continue;
            foreach (var dir in Directory.GetDirectories(raiz).Order(StringComparer.OrdinalIgnoreCase))
            {
                var ruta = Path.Combine(dir, "SKILL.md");
                try
                {
                    if (File.Exists(ruta) && File.ReadLines(ruta).Take(12).Any(l => l.StartsWith(Marca, StringComparison.Ordinal)))
                        lista.Add((Path.GetFileName(dir), ruta));
                }
                catch (IOException) { }
            }
        }
        return lista;
    }

