using Faena.Agente;

namespace Faena.Tests;

/// <summary>`faena skill install|export|list` and `do --learn --skill`: faena writes the Agent Skills that teach other agents to use it.</summary>
public sealed class AgentSkillsTests : IDisposable
{
    private readonly Idioma _idioma = new("en");
    private readonly Consola _c = new();

    public void Dispose()
    {
        _c.Dispose();
        _idioma.Dispose();
    }

    private string Dir => Path.Combine(_c.Carpeta, "skills");

    private void CopiarEjemplo()
    {
        Directory.CreateDirectory(_c.Habilidades);
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !Directory.Exists(Path.Combine(dir.FullName, "examples"))) dir = dir.Parent;
        File.Copy(Path.Combine(dir!.FullName, "examples", "habilidades", "crear-nota.toml"), Path.Combine(_c.Habilidades, "crear-nota.toml"));
    }

    [Fact]
    public void InstallEscribeLaSkillPrincipal()
    {
        Assert.Equal(0, Cli.Run(["skill", "install", "--dir", Dir]));
        var ruta = Path.Combine(Dir, "faena", "SKILL.md");
        Assert.Equal(ruta, _c.Out.ToString().Trim());
        var md = File.ReadAllText(ruta);
        Assert.StartsWith("---\nname: faena\ndescription: \"Hand faena (a local agent) a task", md);
        Assert.Contains("\n---\n\n" + AgentSkills.Marca, md);
        Assert.Contains("`C:\\Tools\\faena\\faena.exe` (in Git Bash: `/c/Tools/faena/faena.exe`)", md);
        Assert.Contains("\"$F\" do \"<clear goal, step by step if it is long>\" --url <website> --background --screenshots", md);
        Assert.Contains("**`--allow` only with the user's authorization**", md);
        Assert.Contains("`3` stopped before something irreversible", md);
        Assert.Contains("informe.json", md);
        Assert.Contains("run it again with `--show`", md);
        Assert.Contains("Never** put passwords", md);
        Assert.Contains("A remote backend (claude, openai) sends the text of the screens off the computer", md);
        Assert.Contains("--use-skill <name> --no-model --param key=value", md);
        Assert.Contains("--ask-in-folder", md);
        Assert.DoesNotContain("Indra", md);
        Assert.DoesNotContain("\r", md);
        // Generated, not written by hand: the same faena gives the same file.
        Assert.Equal(md, AgentSkills.SkillPrincipal("en", AgentSkills.Exe()));
    }

    [Fact]
    public void InstallNoPisaSinForceYConForceGuardaCopia()
    {
        var ruta = Path.Combine(Dir, "faena", "SKILL.md");
        Directory.CreateDirectory(Path.GetDirectoryName(ruta)!);
        File.WriteAllText(ruta, "my own skill");
        Assert.Equal(2, Cli.Run(["skill", "install", "--dir", Dir]));
        Assert.Contains("already exists; use --force", _c.Err.ToString());
        Assert.Equal("my own skill", File.ReadAllText(ruta));

        Assert.Equal(0, Cli.Run(["skill", "install", "--dir", Dir, "--force", "--extra", "LOCAL.md"]));
        Assert.Equal("my own skill", File.ReadAllText(ruta + ".bak"));
        var md = File.ReadAllText(ruta);
        Assert.EndsWith("Notes of this computer (not generated by faena): [LOCAL.md](LOCAL.md).\n", md);
        Assert.Contains("LOCAL.md does not exist yet", _c.Err.ToString());
    }

    [Fact]
    public void InstallEnEspanolYEnElAmbitoDelUsuario()
    {
        Assert.Equal(0, Cli.Run(["skill", "install", "--lang", "es"]));
        var md = File.ReadAllText(Path.Combine(_c.Home, ".claude", "skills", "faena", "SKILL.md"));
        Assert.Contains("# faena: encargarle faenas", md);
        Assert.Contains("\"$F\" hacer \"<objetivo claro, paso a paso si es largo>\" --url <web> --fondo --capturas", md);
        Assert.Contains("## Cuándo usarla", md);
        Assert.Contains("`--permitir` solo con la autorización del usuario", md);
        Assert.Equal(md, AgentSkills.SkillPrincipal("es", AgentSkills.Exe()));
    }

    [Fact]
    public void ExportConvierteUnaHabilidadEnSuSkill()
    {
        CopiarEjemplo();
        Assert.Equal(0, Cli.Run(["skill", "export", "crear-nota", "--dir", Dir]));
        var ruta = Path.Combine(Dir, "faena-crear-nota", "SKILL.md");
        var md = File.ReadAllText(ruta);
        Assert.StartsWith("---\nname: faena-crear-nota\ndescription: \"Do with faena, in a website, what it already knows by heart: Crea una nota con título «<title>» y texto «<text>».", md);
        Assert.Contains(AgentSkills.Marca, md);
        Assert.Contains("It starts in a website: `http://127.0.0.1:8770/index.html`.", md);
        Assert.Contains("| `title` | Comprar pan |", md);
        Assert.Contains("\"/c/Tools/faena/faena.exe\" do \"Crea una nota con título «Comprar pan» y texto «dos barras de la panadería»\" --use-skill crear-nota --background --screenshots", md);
        Assert.Contains("--use-skill crear-nota --no-model --param \"title=Comprar pan\" --param \"text=dos barras de la panadería\" --background --screenshots", md);
        Assert.Contains("**When with a model and when without**", md);
        Assert.Contains("## Anything irreversible still stops", md);
        Assert.Contains("4. Pulsa el botón «Save»", md);
        var h = Habilidades.Cargar(_c.Habilidades).Single();
        Assert.Equal(md, AgentSkills.SkillDeHabilidad(h, "en", AgentSkills.Exe()));

        // Not over an existing one without --force; with it, a .bak.
        Assert.Equal(2, Cli.Run(["skill", "export", "crear-nota", "--dir", Dir]));
        Assert.Equal(0, Cli.Run(["skill", "export", "crear-nota", "--dir", Dir, "--force", "--lang", "es"]));
        Assert.True(File.Exists(ruta + ".bak"));
        Assert.Contains("--habilidad crear-nota --sin-modelo --param", File.ReadAllText(ruta));
        Assert.Contains("## Lo irreversible se para igual", File.ReadAllText(ruta));

        Assert.Equal(2, Cli.Run(["skill", "export", "no-existe", "--dir", Dir]));
        Assert.Contains("There is no skill “no-existe”", _c.Err.ToString());
    }

    [Fact]
    public void ExportSenalaLosPasosQueSePararan()
    {
        var h = Habilidades.Leer("""
            nombre = "avisar"
            descripcion = "Avisa a {para}"
            [parametros]
            para = "Marta"
            [[pasos]]
            tipo = "escribir"
            selector = "#para"
            valor = "{para}"
            desc = "Type “{para}” in the “To” field"
            [[pasos]]
            tipo = "clic"
            selector = "#send"
            desc = "Click the “Send” button"
            """);
        var md = AgentSkills.SkillDeHabilidad(h, "en", @"C:\f\faena.exe");
        Assert.Contains("In this skill these will stop:\n\n- step 2: Click the “Send” button (`send`)\n", md);
        Assert.Contains("- paso 2: Click the “Send” button (`enviar`)", AgentSkills.SkillDeHabilidad(h, "es", @"C:\f\faena.exe"));
    }

    [Fact]
    public void ListSoloEnsenaLasQueEscribioFaena()
    {
        CopiarEjemplo();
        Cli.Run(["skill", "install"]);
        Cli.Run(["skill", "export", "crear-nota", "--dir", Dir]);
        Directory.CreateDirectory(Path.Combine(Dir, "ajena"));
        File.WriteAllText(Path.Combine(Dir, "ajena", "SKILL.md"), "---\nname: ajena\n---\nnot faena's\n");
        _c.Out.GetStringBuilder().Clear();
        Assert.Equal(0, Cli.Run(["skill", "list", "--dir", Dir]));
        var salida = _c.Out.ToString();
        Assert.Contains("faena: " + Path.Combine(_c.Home, ".claude", "skills", "faena", "SKILL.md"), salida);
        Assert.Contains("faena-crear-nota: " + Path.Combine(Dir, "faena-crear-nota", "SKILL.md"), salida);
        Assert.DoesNotContain("ajena", salida);
    }

    [Fact]
    public void AprenderConSkillLaExportaAlAprender()
    {
        _c.Web(new Consola.Correo(), Consola.Escribir, Consola.Guardar, Consola.Terminar);
        var rc = Cli.Run(["do", "Save a draft for Marta", "--url", "https://correo.test/", "--folder", Path.Combine(_c.Carpeta, "run"), "--learn", "draft", "--skill"]);
        Assert.Equal(0, rc);
        var ruta = Path.Combine(_c.Home, ".claude", "skills", "faena-draft", "SKILL.md");
        Assert.Contains("agent skill: " + ruta, _c.Out.ToString());
        var md = File.ReadAllText(ruta);
        Assert.Contains("--use-skill draft --no-model --param \"para=Marta\"", md);
        Assert.Contains("1. Type “{para}” in the “Para” field", md);
    }
}
